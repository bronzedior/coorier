import SwiftUI

extension Font {
    static func relaxe(_ size: CGFloat) -> Font {
        .custom("Relaxe-Regular", fixedSize: size)
    }

    static func schoolbell(_ size: CGFloat) -> Font {
        .custom("Schoolbell-Regular", fixedSize: size)
    }

    static func chelseaMarket(_ size: CGFloat) -> Font {
        .custom("ChelseaMarket-Regular", fixedSize: size)
    }
}
